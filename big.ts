// Conditional / mapped type utilities, applied below to several of the
// generated Shape interfaces - these exercise the checker's structural
// comparison and conditional-type resolution more than plain declarations.
type DeepPartial<T> = T extends object
  ? { [K in keyof T]?: DeepPartial<T[K]> }
  : T

type DeepReadonly<T> = T extends object
  ? { readonly [K in keyof T]: DeepReadonly<T[K]> }
  : T

type PickByType<T, V> = {
  [K in keyof T as T[K] extends V ? K : never]: T[K]
}

type Nullable<T> = { [K in keyof T]: T[K] | null }

function freezeShape<T>(value: T): DeepReadonly<T> {
  return value as DeepReadonly<T>
}

function partialShape<T>(value: T): DeepPartial<T> {
  return value as DeepPartial<T>
}

function numericFieldsOf<T>(value: T): PickByType<T, number> {
  return value as PickByType<T, number>
}



// A discriminated union with many variants, plus an exhaustive switch -
// exercises control-flow narrowing across a wide type.
type AppEvent =
  | { kind: 'click'; x: number; y: number }
  | { kind: 'keydown'; key: string; shiftKey: boolean }
  | { kind: 'resize'; width: number; height: number }
  | { kind: 'scroll'; deltaX: number; deltaY: number }
  | { kind: 'focus'; targetId: number }
  | { kind: 'blur'; targetId: number }
  | { kind: 'submit'; formId: number; values: Record<string, string> }
  | { kind: 'load'; url: string; durationMs: number }
  | { kind: 'error'; message: string; code: number }
  | { kind: 'custom'; name: string; payload: unknown }

function describeEvent(event: AppEvent): string {
  switch (event.kind) {
    case 'click':
      return `click at (${event.x}, ${event.y})`
    case 'keydown':
      return `key ${event.key} shift=${event.shiftKey}`
    case 'resize':
      return `resize to ${event.width}x${event.height}`
    case 'scroll':
      return `scroll by (${event.deltaX}, ${event.deltaY})`
    case 'focus':
      return `focus ${event.targetId}`
    case 'blur':
      return `blur ${event.targetId}`
    case 'submit':
      return `submit ${event.formId} with ${Object.keys(event.values).length} fields`
    case 'load':
      return `load ${event.url} in ${event.durationMs}ms`
    case 'error':
      return `error ${event.code}: ${event.message}`
    case 'custom':
      return `custom ${event.name}`
  }
}

function processEvents(events: AppEvent[]): Record<string, number> {
  const counts: Record<string, number> = {}
  for (const event of events) {
    counts[event.kind] = (counts[event.kind] || 0) + 1
    describeEvent(event)
  }
  return counts
}



